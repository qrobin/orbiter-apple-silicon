#!/usr/bin/env python3
"""Extract the native catalogue from Orbiter's Sol.cfg and body configurations."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[2]
sol=(root/'Src/Celbody/Sol/Config/Sol.cfg').read_text()
entries=[]
for line in sol.splitlines():
    m=re.match(r'(?:(\w+):)?(?:Star|Planet|Moon)\d+\s*=\s*(\w+)',line)
    if m:entries.append((m[2],m[1] or 'Sun'))
def cfg(name):
    files=[p for p in (root/'Src/Celbody').glob('**/Config/'+name+'.cfg') if 'SPICE' not in p.parts]
    if len(files)!=1:raise ValueError((name,files))
    return files[0].read_text(errors='replace')
def number(text,key,default=0):
    m=re.search(r'^\s*'+re.escape(key)+r'\s*=\s*([-+.\deE]+)',text,re.M)
    return float(m[1]) if m else default
def orbitnum(text,key,default=0):
    return number(text,key,number(text.replace(';',''),key,default))
textures={n:n.lower() for n in ['Sun','Mercury','Mars','Jupiter','Saturn','Uranus','Neptune','Moon']}
textures.update(Earth='../earth-8k',Venus='venus_atmosphere')
palette={'Sun':(1,.8,.4),'Venus':(.85,.69,.45),'Mars':(.55,.24,.12),'Moon':(.42,.41,.39),'Io':(.72,.62,.27),'Europa':(.75,.64,.49),'Ganymede':(.40,.35,.29),'Callisto':(.25,.23,.21),'Titan':(.72,.47,.19),'Triton':(.63,.61,.60)}
rows=[]
for name,parent in entries:
    t=cfg(name);el=[orbitnum(t,k) for k in ['SemiMajorAxis','Eccentricity','Inclination','LongAscNode','LongPerihelion','MeanLongitude']]
    epoch=51544.5+(orbitnum(t,'Epoch',2000)-2000)*365.25
    if name=='Moon':el=[384400e3,.0549,.089797,.0,0,0]
    # Rotation precession is frozen at the supplied mean J2000 ecliptic values.
    def ecliptic(key,fallback):
        m=re.search(r';\s*Ecliptic '+key+r' \(rad\):\s*([-+.\deE]+)',t)
        return float(m[1]) if m else fallback
    ob=ecliptic('Obliquity',number(t,'Obliquity'));node=ecliptic('LAN',number(t,'LAN'))
    offset=ecliptic('SidRotOffset',number(t,'SidRotOffset'))
    if name=='Earth':ob=.4090928023;node=0;offset=4.88948754
    color=palette.get(name,(.48,.46,.43));rgb=','.join(map(str,color))
    solid=name not in ['Sun','Jupiter','Saturn','Uranus','Neptune']
    vals=[number(t,'Mass'),number(t,'Size'),number(t,'SidRotPeriod',2160000),offset,ob,node,number(t,'AtmPressure0'),number(t,'AtmDensity0'),number(t,'AtmGasConstant',287),number(t,'AtmGamma',1.4),number(t,'AtmAltLimit')]
    if name=='Earth':vals[-1]=200000
    row='    {BodyId::%s,BodyId::%s,"%s","%s",%s,{%s},%s,{%s}},'%(name,parent,name,textures.get(name,''),','.join(format(v,'.16g') for v in vals),rgb,str(solid).lower(),','.join(format(v,'.16g') for v in el+[epoch]))
    rows.append(row)
(root/'Native/SolarCatalogue.inc').write_text('// Generated by Native/tools/extract_solar_system.py from original body configs.\n'+ '\n'.join(rows)+'\n')
print(len(rows),'bodies extracted')
